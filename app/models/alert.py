"""Alert model for storing behavioral rule violations and psychology alerts."""
from datetime import datetime, timezone
from enum import Enum
from typing import Dict, Any, Optional
from sqlalchemy import Column, Integer, String, Text, DateTime, ForeignKey, JSON
from sqlalchemy.orm import relationship

from app.database import Base


class AlertSeverity(str, Enum):
    INFO = "INFO"
    WARNING = "WARNING"
    CRITICAL = "CRITICAL"


class AlertType(str, Enum):
    RULE_VIOLATION = "RULE_VIOLATION"
    MAX_RISK_EXCEEDED = "MAX_RISK_EXCEEDED"
    OVERTRADING_AFTER_LOSS = "OVERTRADING_AFTER_LOSS"
    REVENGE_TRADING = "REVENGE_TRADING"
    LATE_BREAKOUT_CHASE = "LATE_BREAKOUT_CHASE"
    REQUIRE_STOP_LOSS = "REQUIRE_STOP_LOSS"
    MAX_TRADES_EXCEEDED = "MAX_TRADES_EXCEEDED"
    MAX_DAILY_LOSS = "MAX_DAILY_LOSS"
    MODEL_RISK = "MODEL_RISK"


class Alert(Base):
    """Behavioral and rule violation alert generated by the rule engine."""
    __tablename__ = "alerts"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True)
    alert_type = Column(String(50), nullable=False, index=True)
    severity = Column(String(20), default=AlertSeverity.WARNING.value, nullable=False)
    message = Column(Text, nullable=False)
    context_json = Column(JSON, default=dict, nullable=False)
    created_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
        index=True
    )

    user = relationship("User", backref="alerts")

    def __repr__(self) -> str:
        return f"<Alert id={self.id} user={self.user_id} type={self.alert_type} severity={self.severity}>"

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "user_id": self.user_id,
            "alert_type": self.alert_type,
            "severity": self.severity,
            "message": self.message,
            "context_json": self.context_json,
            "created_at": self.created_at.isoformat() if self.created_at else None,
        }
